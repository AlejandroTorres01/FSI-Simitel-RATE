    private void TFValorKeyPressed(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_TFValorKeyPressed
        char tecla = evt.getKeyChar();
        if (tecla == '\n') {
            String call = "{call filtrar_medicamento(?)}";

            try {
                CallableStatement cs = (CallableStatement) cnx.con.prepareCall(call);
                cs.setString(1, TFValor.getText());
                cs.execute();

            } catch (SQLException ex) {
                System.out.println("ERROR al llamar al procedimiento");
            }
        }
    }//GEN-LAST:event_TFValorKeyPressed

