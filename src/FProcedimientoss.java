    private void LFotoMousePressed(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_LFotoMousePressed
        JFileChooser fc = new JFileChooser(System.getProperty("user.dir") + "/imagenes/");
        if (fc.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            archivoFoto = fc.getSelectedFile().getPath();
            foto = new ImageIcon(archivoFoto);
            LFoto.setIcon(new ImageIcon(Conexion2.escalarImagen(foto.getImage(), LFoto.getWidth(), LFoto.getHeight())));
        }
    }//GEN-LAST:event_LFotoMousePressed

    private void BInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BInsertarActionPerformed
        try {
            java.sql.Date fecha = new java.sql.Date(((java.util.Date) SFecha.getValue()).getTime());

            java.sql.CallableStatement cs = cnx.con.prepareCall("{CALL insertar_pacientes(?, ?, ?, ?, ?, ?, ?, ?)}");

            cs.setString(1, TCodigo.getText());
            cs.setString(2, TNombre.getText());
            cs.setString(3, CBSexo.getSelectedItem().toString());
            cs.setDate(4, fecha);
            cs.setString(5, CBTSangre.getSelectedItem().toString());
            cs.setString(6, CBRaza.getSelectedItem().toString());
            cs.setString(7, CBReligion.getSelectedItem().toString());
            cs.setBytes(8, Files.readAllBytes(Path.of(archivoFoto)));

            cs.execute();
            cs.close();

            JOptionPane.showMessageDialog(this, "Paciente guardado");
            cnx.entablar(todo, TConsultas, 45, 255, 45, 90, 45, 45, 45, 100);

            
            TCodigo.setText("");
            TNombre.setText("");
            CBSexo.setSelectedIndex(0);
            SFecha.setValue(new java.util.Date());
            CBTSangre.setSelectedIndex(0);
            CBRaza.setSelectedIndex(0);
            CBReligion.setSelectedIndex(0);
            LFoto.setIcon(null);
            archivoFoto = "";

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al inngresar paciente, verifica los campos" + ex.getMessage());
        }
    }//GEN-LAST:event_BInsertarActionPerformed

